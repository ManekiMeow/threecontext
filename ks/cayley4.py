PAIRS = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]


def orbits_under(G, autos):
    """Orbits of the group generated by the automorphisms `autos` (arrays) on the elements of G."""
    seen, orbits = set(), []
    for a in range(G.n):
        if a in seen:
            continue
        orb, frontier = {a}, [a]
        while frontier:
            x = frontier.pop()
            for phi in autos:
                y = int(phi[x])
                if y not in orb:
                    orb.add(y)
                    frontier.append(y)
        seen |= orb
        orbits.append(sorted(orb))
    return orbits


def multiplier_orbits(p, e):
    """Z_p (as groups.cyclic(p)) with M = the e-th powers in Z_p^*: orbits {0} and the e classes."""
    g = next(a for a in range(2, p) if len({pow(a, i, p) for i in range(1, p)}) == p - 1)
    m = pow(g, e, p)
    return orbits_under(groups_mod.cyclic(p), [np.array([(m * x) % p for x in range(p)])])


class Cayley4:
    """SAT encoding. With `orbits` (the orbits of a group M of automorphisms of Γ), only M-invariant
    connection sets are allowed: one variable per (pair, orbit), and every constraint family is
    generated from orbit representatives only (the constraints are M-invariant)."""

    def __init__(self, G, deg_min=9, total_min=30, orbits=None):
        self.G, self.d = G, G.n
        self.pool = IDPool()
        self.orbits = orbits or [[s] for s in range(self.d)]
        self.orbit_of = np.zeros(self.d, dtype=int)
        for i, orb in enumerate(self.orbits):
            self.orbit_of[orb] = i
        self.reps = [orb[0] for orb in self.orbits]
        self.y = {p: [self.pool.id(("x",) + p + (i,)) for i in range(len(self.orbits))] for p in PAIRS}
        self.x = {p: [self.y[p][self.orbit_of[s]] for s in range(self.d)] for p in PAIRS}
        self.cls = []
        self.deg_min, self.total_min = deg_min, total_min
        self.encode()

    def symmetry_breaking(self, limit=40):
        """Lex-leader clauses for automorphisms of Γ (those permuting the orbits) and for
        permutations of bases 0, 1, 2."""
        xs = [self.y[p][i] for p in PAIRS for i in range(len(self.orbits))]
        maps = []
        orbset = {tuple(o) for o in self.orbits}
        for phi in automorphisms(self.G, limit):
            if all(tuple(sorted(int(phi[s]) for s in o)) in orbset for o in self.orbits):
                maps.append([self.mem(k, l, int(phi[r])) for k, l in PAIRS for r in self.reps])
        for perm in ((1, 0, 2, 3), (0, 2, 1, 3)):
            # the configuration with bases relabelled k -> perm[k]: S'_{perm k, perm l} = S_kl
            inv = {perm[k]: k for k in range(4)}
            maps.append([self.mem(inv[k], inv[l], r) for k, l in PAIRS for r in self.reps])
        for ys in maps:
            self.cls.extend(lex_geq(self.pool, xs, ys))
        return len(maps)

    def quotient_constraints(self, ms=(2, 3)):
        """Forbid skeletons that map onto a bad residue pattern for some homomorphism onto Z_m."""
        added = 0
        for m in ms:
            phis = homomorphisms_onto_cyclic(self.G, m)
            if not phis:
                continue
            maximal, _ = bad_quotient_patterns(m)
            for phi in phis:
                r = {}
                for p in PAIRS:
                    for a in range(m):
                        v = self.pool.id(("res", m, tuple(phi.tolist())[:8], p, a, added))
                        members = [self.x[p][s] for s in range(self.d) if phi[s] == a]
                        self.cls.append([-v] + members)
                        self.cls.extend([[-x, v] for x in members])
                        r[(p, a)] = v
                for B in maximal:
                    self.cls.append([r[b] for b in r if b not in B])
                added += 1
        return added

    def mem(self, k, l, s):
        """Literal for s ∈ S_kl."""
        if k < l:
            return self.x[(k, l)][s]
        return self.x[(l, k)][int(self.G.inv[s])]

    def q(self, g, h):
        """g⁻¹h."""
        return int(self.G.mul[self.G.inv[g]][h])

    def AND(self, *lits):
        v = self.pool.id(("and",) + tuple(sorted(lits)))
        if ("def", v) not in self.pool.obj2id:
            self.pool.id(("def", v))
            self.cls.extend([[-v, a] for a in lits])
            self.cls.append([v] + [-a for a in lits])
        return v

    def encode(self):
        d, mem, q, reps = self.d, self.mem, self.q, self.reps
        for k in range(3):                                            # normalisation
            self.cls.append([mem(3, k, 0)])
        k4 = set()
        for g0 in reps:                                               # (K4), up to the orbit action
            for g1, g2 in itertools.product(range(d), repeat=2):
                k4.add(tuple(sorted({-mem(3, 0, g0), -mem(3, 1, g1), -mem(3, 2, g2),
                                     -mem(0, 1, q(g0, g1)), -mem(0, 2, q(g0, g2)), -mem(1, 2, q(g1, g2))})))
        self.cls.extend(list(c) for c in k4)
        enc = EncType.seqcounter
        self.cards = []                                               # (lits, bound, enforcing literal)
        for p in PAIRS:                                               # (DEG)
            self.cards.append((self.x[p], self.deg_min, None))
        for k in range(4):
            others = [l for l in range(4) if l != k]
            lits = sum((self.x[tuple(sorted((k, l)))] for l in others), [])
            self.cards.append((lits, self.total_min, None))
            for l in others:                                          # Theorem 5
                sel = self.pool.id(("sel", k, l))
                self.cards.append((self.x[tuple(sorted((k, l)))], 10, sel))
                for m in others:
                    if m != l:
                        self.cards.append((self.x[tuple(sorted((k, m)))], 12, -sel))
        for lits, bound, cond in self.cards:
            # repeated literals (orbit variables) count with multiplicity: give each copy its own
            # variable, equivalent to the orbit variable
            if len(set(lits)) < len(lits):
                copies = []
                for i, a in enumerate(lits):
                    z = self.pool.id(("copy", a, i, len(self.cls)))
                    self.cls.extend([[-z, a], [z, -a]])
                    copies.append(z)
                lits = copies
            cnf = CardEnc.atleast(lits, bound=bound, vpool=self.pool, encoding=enc).clauses
            self.cls.extend(cnf if cond is None else [c + [-cond] for c in cnf])

        def not_exactly_one(ys, guard):
            """Clauses: guard or (the number of true c's is not 1), ys listed per element c."""
            cnt = {}
            for y in ys:
                cnt[y] = cnt.get(y, 0) + 1
            distinct = list(cnt)
            for y in distinct:
                if cnt[y] == 1:                         # a variable shared by >= 2 c's never counts 1
                    self.cls.append(guard + [-y] + [z for z in distinct if z != y])
        for k, l in PAIRS:                                            # (C2), (C4), different bases
            for m in range(4):
                if m in (k, l):
                    continue
                for s in reps:
                    ys = [self.AND(mem(k, m, c), mem(m, l, q(c, s))) for c in range(d)]
                    self.cls.append([-mem(k, l, s)] + list(dict.fromkeys(ys)))
                    not_exactly_one(ys, [mem(k, l, s)])
        for k in range(4):                                            # (C4), same basis
            for m in range(4):
                if m == k:
                    continue
                for s in reps:
                    if s != 0:
                        not_exactly_one([self.AND(mem(k, m, c), mem(m, k, q(c, s))) for c in range(d)], [])
        for k, l, m in itertools.combinations(range(4), 3):           # (TRI)
            self.cls.append(list(dict.fromkeys(self.AND(mem(k, l, s), mem(k, m, c), mem(l, m, q(s, c)))
                                               for s in reps for c in range(d))))

    def sets(self, model):
        val = set(v for v in model if v > 0)
        S = {}
        for k in range(4):
            for l in range(4):
                if k != l:
                    S[(k, l)] = [s for s in range(self.d) if self.mem(k, l, s) in val]
        return S

    def neighbourhood(self, S, k):
        """Vertices (l, g) of N((k, e)) and their adjacency (non-orthogonality) matrix."""
        V = [(l, g) for l in range(4) if l != k for g in S[(k, l)]]
        sets = {key: set(v) for key, v in S.items()}
        A = np.zeros((len(V), len(V)), dtype=bool)
        for i, (l, g) in enumerate(V):
            for j, (m, h) in enumerate(V):
                if l != m and self.q(g, h) in sets[(l, m)]:
                    A[i, j] = True
        return V, A

    def block_clause(self, S, k, V, A, side=None):
        """Sound blocking clause for a neighbourhood with theta(complement) < 3: some new vertex,
        or some new edge among the present vertices. If the neighbourhood is bipartite with sides
        `side`, edges between the two sides keep it bipartite, so only same-side pairs are listed."""
        lits = set()
        for l in range(4):
            if l != k:
                present = set(S[(k, l)])
                lits.update(self.mem(k, l, g) for g in range(self.d) if g not in present)
        for i, (l, g) in enumerate(V):
            for j, (m, h) in enumerate(V):
                if l < m and not A[i, j] and (side is None or side[i] == side[j]):
                    lits.add(self.mem(l, m, self.q(g, h)))
        return sorted(lits)

    def full_graph(self, S):
        d = self.d
        sets = {key: set(v) for key, v in S.items()}
        X = np.zeros((4 * d, 4 * d), dtype=bool)
        for k, l in itertools.permutations(range(4), 2):
            for g in range(d):
                for h in range(d):
                    if self.q(g, h) in sets[(k, l)]:
                        X[k * d + g, l * d + h] = True
        return X


def automorphisms(G, limit=40, seed=0):
    """Up to `limit` automorphisms of G (brute force over images of a generating set)."""
    n = G.n
    gens, H = [], {0}
    for a in range(1, n):                                  # greedy generating set
        if a not in H:
            gens.append(a)
            H = {0}
            frontier = [0]
            while frontier:
                x = frontier.pop()
                for g in gens:
                    y = int(G.mul[x][g])
                    if y not in H:
                        H.add(y)
                        frontier.append(y)
            if len(H) == n:
                break

    def order(a):
        k, x = 1, a
        while x != 0:
            x, k = int(G.mul[x][a]), k + 1
        return k
    # every element as a word in the generators (BFS tree)
    word = {0: []}
    frontier = [0]
    while frontier:
        x = frontier.pop(0)
        for i, g in enumerate(gens):
            y = int(G.mul[x][g])
            if y not in word:
                word[y] = word[x] + [i]
                frontier.append(y)
    cands = [[b for b in range(n) if order(b) == order(g)] for g in gens]
    rng = np.random.default_rng(seed)
    out, seen = [], set()
    combos = list(itertools.product(*cands))
    rng.shuffle(combos)
    for imgs in combos:
        phi = np.zeros(n, dtype=int)
        for x, w in word.items():
            y = 0
            for i in w:
                y = int(G.mul[y][imgs[i]])
            phi[x] = y
        if len(set(phi.tolist())) < n:
            continue
        if all(phi[G.mul[a][b]] == G.mul[phi[a]][phi[b]] for a in range(n) for b in range(n)):
            key = tuple(phi.tolist())
            if key not in seen and key != tuple(range(n)):
                seen.add(key)
                out.append(phi)
                if len(out) >= limit:
                    break
    return out


def homomorphisms_onto_cyclic(G, m):
    """Surjective homomorphisms G -> Z_m, one per kernel."""
    out, kernels = [], set()
    n = G.n
    # brute force over images of a generating set
    gens, H = [], {0}
    for a in range(1, n):
        if a not in H:
            gens.append(a)
            H, frontier = {0}, [0]
            while frontier:
                x = frontier.pop()
                for g in gens:
                    y = int(G.mul[x][g])
                    if y not in H:
                        H.add(y)
                        frontier.append(y)
            if len(H) == n:
                break
    word, frontier = {0: []}, [0]
    while frontier:
        x = frontier.pop(0)
        for i, g in enumerate(gens):
            y = int(G.mul[x][g])
            if y not in word:
                word[y] = word[x] + [i]
                frontier.append(y)
    for imgs in itertools.product(range(m), repeat=len(gens)):
        phi = np.array([sum(imgs[i] for i in word[x]) % m for x in range(n)])
        if len(set(phi.tolist())) < m:
            continue
        if all(phi[G.mul[a][b]] == (phi[a] + phi[b]) % m for a in range(n) for b in range(n)):
            ker = frozenset(np.where(phi == 0)[0].tolist())
            if ker not in kernels:
                kernels.add(ker)
                out.append(phi)
    return out


def bad_quotient_patterns(m):
    """Maximal 'residue patterns' over Z_m whose four vertex neighbourhoods include a bipartite one.

    A pattern is R_kl ⊆ Z_m for the six pairs (bit (pair, a) = [a ∈ R_kl]), with 0 ∈ R_k3 for
    k = 0, 1, 2. If a Cayley skeleton has S_kl ⊆ phi^{-1}(R_kl) for a homomorphism phi onto Z_m,
    phi maps every neighbourhood homomorphically into the pattern's neighbourhood, so a bipartite
    pattern neighbourhood forces a bipartite (theta = 2) neighbourhood. Badness is inherited by
    sub-patterns, so it suffices to forbid being contained in a maximal bad pattern."""
    bits = [(p, a) for p in PAIRS for a in range(m)]
    fixed = {((k, 3), 0) for k in range(3)}
    free = [b for b in bits if b not in fixed]

    def R(pat, k, l):
        if k < l:
            return {a for a in range(m) if ((k, l), a) in pat}
        return {(-a) % m for a in range(m) if ((l, k), a) in pat}

    def bad(pat):
        for p in range(4):
            V = [(l, a) for l in range(4) if l != p for a in R(pat, p, l)]
            A = np.zeros((len(V), len(V)), dtype=bool)
            for i, (l, a) in enumerate(V):
                for j, (l2, b) in enumerate(V):
                    if l != l2 and (b - a) % m in R(pat, l, l2):
                        A[i, j] = True
            if two_colouring(A) is not None:
                return True
        return False
    bads = []
    for mask in range(1 << len(free)):
        pat = set(fixed) | {free[i] for i in range(len(free)) if mask >> i & 1}
        if bad(pat):
            bads.append(mask)
    badset = set(bads)
    maximal = [b for b in bads if not any((b | (1 << i)) in badset for i in range(len(free)) if not b >> i & 1)]
    return [set(fixed) | {free[i] for i in range(len(free)) if b >> i & 1} for b in maximal], len(bads)


def lex_geq(pool, xs, ys):
    """Clauses for xs >=_lex ys (bit vectors of literals), exact prefix-equality encoding."""
    cls = []
    a = pool.id(("lex", len(pool.obj2id)))
    cls.append([a])
    for x, y in zip(xs, ys):
        cls.append([-a, x, -y])                             # equal so far => x >= y
        b = pool.id(("lex", len(pool.obj2id)))
        cls += [[-b, a], [-b, -x, y], [-b, x, -y], [-a, -x, -y, b], [-a, x, y, b]]
        a = b
    return cls


def two_colouring(A):
    """A proper 2-colouring of the graph A (list of 0/1), or None if it has an odd cycle."""
    n = len(A)
    side = [-1] * n
    for s in range(n):
        if side[s] >= 0:
            continue
        side[s] = 0
        stack = [s]
        while stack:
            v = stack.pop()
            for w in np.where(A[v])[0]:
                if side[w] < 0:
                    side[w] = 1 - side[v]
                    stack.append(w)
                elif side[w] == side[v]:
                    return None
    return side


def theta_complement(V, A):
    """theta of the exclusivity graph of a neighbourhood: orthogonal = same basis or non-adjacent."""
    n = len(V)
    part = np.array([v[0] for v in V])
    zero = ((part[:, None] == part[None, :]) | ~A) & ~np.eye(n, dtype=bool)
    X = cp.Variable((n, n), symmetric=True)
    cons = [X >> 0, cp.trace(X) == 1, cp.multiply(zero.astype(float), X) == 0]
    prob = cp.Problem(cp.Maximize(cp.sum(X)), cons)
    prob.solve(solver=cp.CLARABEL)
    return prob.value


def check_conditions(X, d):
    """Brute-force re-check of (K4), (DEG), (C2), (C4), (TRI) on a 4d x 4d non-orthogonality matrix."""
    part = np.arange(4 * d) // d
    issues = []
    for v in range(4 * d):
        degs = [int(X[v, part == l].sum()) for l in range(4) if l != part[v]]
        if min(degs) < 9 or sum(degs) < 30:
            issues.append(("DEG", v, degs))
    for a in range(4 * d):
        for b in range(a + 1, 4 * d):
            for m in range(4):
                if m in (part[a], part[b]):
                    continue
                common = int((X[a] & X[b] & (part == m)).sum())
                if part[a] != part[b] and X[a, b] and common == 0:
                    issues.append(("C2", a, b, m))
                if (part[a] == part[b] or not X[a, b]) and common == 1:
                    issues.append(("C4", a, b, m))
    for v in range(d):                                   # K4 through part-0 vertices
        for w in np.where(X[v] & (part == 1))[0]:
            for u in np.where(X[v] & X[w] & (part == 2))[0]:
                if (X[v] & X[w] & X[u] & (part == 3)).any():
                    issues.append(("K4", v, w, u))
    for k, l, m in itertools.combinations(range(4), 3):
        tri = any((X[a] & X[b] & (part == m)).any()
                  for a in np.where(part == k)[0] for b in np.where(X[a] & (part == l))[0])
        if not tri:
            issues.append(("TRI", k, l, m))
    return issues


def colourable_complement(X, d):
    """0-1 colouring of the complement (orthogonality graph) with the four bases as contexts.
    Further bases inside the complement only add constraints, so UNSAT here is a KS proof."""
    n = 4 * d
    part = np.arange(n) // d
    cl = [[a + 1 for a in range(k * d, (k + 1) * d)] for k in range(4)]
    cl += [[-(a + 1), -(b + 1)] for a in range(n) for b in range(a + 1, n)
           if part[a] == part[b] or not X[a, b]]
    with Cadical153(bootstrap_with=cl) as s:
        return s.solve()


def realize(X, d, restarts=4, iters=4000, seed=0, tol=1e-9):
    """Douglas–Rachford for four orthonormal bases of C^d with the zero pattern of X.

    A = {4Q : Q a rank-d orthogonal projector} (Gram matrices of four bases), B = {Hermitian
    matrices with identity diagonal blocks and zeros where X has no edge}. Returns the smallest
    residual ||P_B(P_A(x)) - P_A(x)|| found, and the corresponding Gram matrix."""
    n = 4 * d
    part = np.arange(n) // d
    zero = ~X & (part[:, None] != part[None, :])
    diag = part[:, None] == part[None, :]
    eye = np.eye(n)
    rng = np.random.default_rng(seed)

    def PA(M):
        w, U = np.linalg.eigh((M + M.conj().T) / 2)
        U = U[:, -d:]
        return 4 * U @ U.conj().T

    def PB(M):
        M = M.copy()
        M[zero] = 0
        M[diag] = eye[diag]
        return M

    best, best_P = np.inf, None
    for _ in range(restarts):
        V = np.hstack([np.linalg.qr(rng.normal(size=(d, d)) + 1j * rng.normal(size=(d, d)))[0]
                       for _ in range(4)])
        x = V.conj().T @ V
        for it in range(iters):
            pb = PB(x)
            x = x + PA(2 * pb - x) - pb
            if it % 100 == 99:
                pa = PA(PB(x))
                r = np.linalg.norm(PB(pa) - pa)
                if r < best:
                    best, best_P = r, pa
                if r < tol:
                    return best, best_P
    return best, best_P


def search(G, time_limit, log=print, max_candidates=10, realize_restarts=3, symmetry=True, blocks=None,
           solver_name="cadical195", dense_phase=False, progress=600, quotients=True, orbits=None):
    """CEGAR search over Cayley skeletons of G. `blocks` (a list) receives every learned clause and may
    contain clauses from an earlier run, which are added first (resume)."""
    t0 = time.time()
    enc = Cayley4(G, orbits=orbits)
    nsym = enc.symmetry_breaking() if symmetry else 0
    nquo = enc.quotient_constraints() if quotients else 0
    stats = dict(group=G.name, d=G.n, vars=enc.pool.top, clauses=len(enc.cls), symmetries=nsym, quotients=nquo,
                 models=0,
                 bipartite_blocks=0, theta_blocks=0, candidates=[], status=None)
    blocks = [] if blocks is None else blocks
    last = t0
    with Solver(name=solver_name, bootstrap_with=enc.cls + blocks) as solver:
        if dense_phase:
            solver.set_phases([v for p in PAIRS for v in enc.x[p]])
        while True:
            if time.time() - t0 > time_limit:
                stats["status"] = "timeout"
                break
            if time.time() - last > progress:
                last = time.time()
                log(f"   {G.name}: {stats['models']} models, {stats['bipartite_blocks']} bipartite and "
                    f"{stats['theta_blocks']} theta blocks, {len(stats['candidates'])} candidates, "
                    f"{round(last - t0)} s")
            solver.conf_budget(20000)
            res = solver.solve_limited()
            if res is None:
                continue
            if res is False:
                stats["status"] = "UNSAT"
                break
            stats["models"] += 1
            S = enc.sets(solver.get_model())
            ok = True
            for k in (3, 0, 1, 2):
                if time.time() - t0 > time_limit:
                    ok = False
                    break
                V, A = enc.neighbourhood(S, k)
                side = two_colouring(A)
                if side is not None:                       # bipartite: theta = 2
                    blocks.append(enc.block_clause(S, k, V, A, side))
                    solver.add_clause(blocks[-1])
                    stats["bipartite_blocks"] += 1
                    ok = False
                    continue
                th = theta_complement(V, A)
                if th < 3 - 1e-6:
                    blocks.append(enc.block_clause(S, k, V, A))
                    solver.add_clause(blocks[-1])
                    stats["theta_blocks"] += 1
                    ok = False
            if not ok:
                continue
            X = enc.full_graph(S)
            cand = dict(sizes={f"{k}{l}": len(S[(k, l)]) for k, l in PAIRS},
                        sets={f"{k}{l}": S[(k, l)] for k, l in PAIRS},
                        issues=check_conditions(X, G.n)[:5],
                        complement_colourable=colourable_complement(X, G.n))
            iters = 4000 if G.n <= 40 else 1500 if G.n <= 80 else 500
            res_r, _ = realize(X, G.n, restarts=realize_restarts, iters=iters)
            cand["realize_residual"] = float(res_r)
            stats["candidates"].append(cand)
            log(f"   candidate {len(stats['candidates'])}: sizes {cand['sizes']} "
                f"issues {cand['issues']} colourable {cand['complement_colourable']} "
                f"residual {res_r:.2e}")
            if res_r < 1e-9:
                log("   *** realizable candidate found ***")
            blocks.append(sorted({-enc.mem(k, l, s) if s in S[(k, l)] else enc.mem(k, l, s)
                                  for k, l in PAIRS for s in range(G.n)}))
            solver.add_clause(blocks[-1])
            if len(stats["candidates"]) >= max_candidates:
                stats["status"] = "candidate limit"
                break
    stats["seconds"] = round(time.time() - t0, 1)
    return stats


