"""Cayley four-partite K4-free graphs as candidate four-context KS sets (Route A), RESULTS.md §3.12.

Family. Γ is a finite group of order d. Vertex (k, g) is ray g of basis B_k (k = 0..3), and
(k, g) ~ (l, h) (non-orthogonal) iff g⁻¹h ∈ S_kl, with S_lk = S_kl⁻¹. These are exactly the
non-orthogonality graphs of four bases on which Γ acts regularly. By Corollary 12a such a union is
KS iff the graph is K4-free (Route A), and then the 0-1 colouring of the complement fails
automatically: a colouring would pick one ray per basis, pairwise non-orthogonal, i.e. a K4.
So the questions are which K4-free graphs pass the necessary conditions, and whether any of
them is realizable.

Necessary conditions (all proved in RESULTS.md §2–3), encoded in SAT:
  (K4)   no transversal K4, i.e. the neighbourhood of (3, e) is triangle-free;
  (DEG)  |S_kl| >= 9 for all k != l (Lemma 14); every vertex has >= 30 neighbours (Corollary 6);
         if |S_kl| = 9 then |S_km| >= 12 for the other two m (Theorem 5);
  (C2)   adjacent rays have a common neighbour in each other basis;
  (C4)   orthogonal rays (different or same basis) have 0 or >= 2 common neighbours in each other
         basis;
  (TRI)  every three bases contain a triangle (three bases are never KS, §3.4).
Normalisation: e ∈ S_3k for k = 0, 1, 2 (relabel each basis by a right translation).
Symmetry breaking: lex-leader clauses for sampled automorphisms of Γ and for permutations of
bases 0, 1, 2. Quotient constraints: a homomorphism Γ -> Z_m (m = 2, 3) maps every neighbourhood
homomorphically into the neighbourhood of a "residue pattern"; patterns with a bipartite
neighbourhood are forbidden, since then theta = 2 (bad_quotient_patterns()).
Orbits (optional): restrict to connection sets invariant under a group M of automorphisms of Γ
(e.g. the multiplier family over Z_p, multiplier_orbits()); then every constraint family is
generated from orbit representatives only.

CEGAR on the local GHZ condition. The neighbourhood of every ray is a three-context GHZ paradox,
so theta(complement of N(v)) = 3. One SDP per basis checks this; a failure is blocked by the sound
clause "N(v) gains a vertex or one of its non-edges becomes an edge" (theta of the complement can
only grow then). A model passing all four checks is a candidate. Candidates get the 0-1
colouring check and a realizability test (Douglas–Rachford on the Gram matrix, see realize()).
"""
